export const CHECKLIST_ITEMS = [
    // 範例資料：大樓 (ConfigSno: 1)
    { configSno: 1, location: "客餐廳", item: "地磚/地板", ino: "1001" },
    { configSno: 1, location: "客餐廳", item: "牆面平整", ino: "1002" },
    { configSno: 1, location: "廚房", item: "流理台", ino: "1003" },
    // 範例資料：透天 (ConfigSno: 3)
    { configSno: 3, location: "1F", item: "大門", ino: "3001" },
];

// 取得該設定類型 (例如: 1=大樓) 的所有區域
export const getLocations = (configSno) => {
    const items = CHECKLIST_ITEMS.filter(i => i.configSno === configSno);
    const locations = [...new Set(items.map(i => i.location))];
    const order = ['1F', '2F', '3F', '客餐廳', '廚房', '主臥室', '次臥室', '衛浴', '陽台'];
    return locations.sort((a, b) => {
        const idxA = order.indexOf(a);
        const idxB = order.indexOf(b);
        if (idxA !== -1 && idxB !== -1) return idxA - idxB;
        if (idxA !== -1) return -1;
        if (idxB !== -1) return 1;
        return a.localeCompare(b);
    });
};

// 取得該區域的分類項目
export const getGroupedItems = (configSno, location) => {
    const items = CHECKLIST_ITEMS.filter(i => i.configSno === configSno && i.location === location);
    return {
        "檢查項目": items
    };
};

